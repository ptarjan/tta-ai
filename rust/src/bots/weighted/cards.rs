/// `_BOARD_CREDIT_KEYS`/`_board_credit_key`: the per-type offset on top of
/// `card_board_credit` for a card whose pricing is board-aware
/// ([`board_yields::is_swap_type`] for leader/government/wonder, plus
/// action, plus the military-deck's Bonus class). `None` for every other
/// type -- there is nothing to offset.
///
/// Deliberately exhaustive over every [`CardType`] variant, NOT a `match`
/// with a trailing `_ => None` -- docs/OPEN_ITEMS.md's own account of why
/// `Bonus` needed a branch here is exactly the bug shape a wildcard arm
/// invites: a card category present in [`CardType`] but silently absent
/// from this registry, with nothing failing when they disagree until
/// someone asks why a whole class prices as if it isn't there
/// (`row_pressure` was blind to `class:bonus` for precisely this reason).
/// Adding a category later is a compile error here until a human decides
/// its credit key on purpose, matching `WeightKey::group`'s own reasoning
/// in `weights.rs` for banning the same wildcard shape. See also
/// `tests::board_credit_key_is_exhaustive_and_only_none_for_types_with_no_board_credit_concept`.
pub fn board_credit_key(id: CardId) -> Option<WeightKey> {
    use CardType::*;
    match id.get().kind {
        Leader => Some(WeightKey::CardBoardLeader),
        Government => Some(WeightKey::CardBoardGovernment),
        Action => Some(WeightKey::CardBoardAction),
        Wonder => Some(WeightKey::CardBoardWonder),
        Bonus => Some(WeightKey::CardBoardBonus),

        // No board-aware pricing concept exists in THIS table for these --
        // not "unpriced", just priced a different way. A build (Farm/Mine/
        // urban/unit/SpecialTech) is priced by `tech_value` gated on
        // `tech_board_credit` directly, never through this per-type OFFSET
        // table at all (see `card_potential`'s dispatch, which returns
        // before ever calling this function for a levelled type). Tactic/
        // Aggression/War/Pact/Event (docs/OPEN_ITEMS.md item 2, closed
        // 2026-08-06) now follow the exact same shape: `tactic_value`/
        // `aggression_value`/`war_hand_value`/`pact_value`/`event_prepare_
        // value`, each gated on its own `*_board_credit`, dispatched from
        // `card_potential` before this function is ever reached for one of
        // the five. Territory is priced a third way, through the static
        // table (`card_yields`'s `YieldKind::Territory` branch,
        // `territory_credit`) -- see this module's top doc comment for why
        // Territory was never truly part of item 2's "prices at 0.0" claim
        // despite being named alongside these five in earlier drafts of
        // this comment.
        Farm | Mine | Lab | Temple | Library | Arena | Theater | Infantry | Cavalry | Artillery
        | Air | SpecialTech | Tactic | Aggression | War | Pact | Territory | Event => None,
    }
}

/// `_swap_type`: `Some(kind)` for a single-slot card (leader/government),
/// else `None`. Deliberately [`board_yields::is_single_slot`], NOT
/// [`board_yields::is_swap_type`]: a wonder is priced by a swap diff too, but
/// two wonders in hand can both be built, so collapsing them the way two
/// leaders (only one of which you can ever hold) collapse would be wrong.
/// See the two predicates' own doc comments in `board_yields.rs`.
pub fn swap_type(id: CardId) -> Option<CardType> {
    let kind = id.get().kind;
    board_yields::is_single_slot(kind).then_some(kind)
}

// ---------------------------------------------- the two ring-fenced yields

/// `_RESTRICTED_TO_FEATURE`: `resource_discount`/`restricted_resources` are
/// not live `evaluate` coordinates (`features()` emits neither), so no game
/// the league plays can put a gradient on them directly. Both are RESOURCES
/// though, so [`yield_marginal`] reroutes them through `resource_stock`'s
/// marginal instead, at a credit that is 1.0 (a discount is worth a whole
/// resource: the build was already going to happen) for the first and a
/// weight (`restricted_resource_credit`, an upper bound a player who builds
/// no units this turn realises none of) for the second. See the Python
/// source's own extensive derivation on `_RESTRICTED_TO_FEATURE`, not
/// reproduced here.
fn restricted_to_feature(key: WeightKey) -> Option<(WeightKey, RestrictedCredit)> {
    match key {
        WeightKey::ResourceDiscount => Some((WeightKey::ResourceStock, RestrictedCredit::Fixed(1.0))),
        WeightKey::RestrictedResources => {
            Some((WeightKey::ResourceStock, RestrictedCredit::Weight(WeightKey::RestrictedResourceCredit)))
        }
        _ => None,
    }
}

/// Whether a ring-fenced feature's credit is the constant `1.0`
/// (`resource_discount`) or itself a weight to look up
/// (`restricted_resource_credit`) -- mirrors Python's `credit` being either a
/// bare `float` or a dict key string, disambiguated there by `isinstance
/// (credit, float)`.
enum RestrictedCredit {
    Fixed(f64),
    Weight(WeightKey),
}

/// `_yield_marginal`: [`rivals::feature_marginal`], plus the two ring-fenced
/// pseudo-features above. `idx: u8`/`late: Option<f64>` match `rivals::
/// feature_marginal`'s own signature exactly (see this module's top doc
/// comment on the `idx` width mismatch with `board_yields.rs`); `ctx` is
/// always `None` here, matching Python's `_yield_marginal(key, state, idx,
/// w, late)` -- it never threads a `RivalContext` through, unlike
/// `strength_marginal`'s other callers.
///
/// Both ring-fenced branches clamp their `feature_marginal` read to
/// `max(0.0, ...)` for the same reason [`YieldKind::Cost`] does: a GAIN
/// (a discount, a ring-fenced resource) must never read as a loss because a
/// hill climb drove `resource_stock` negative.
pub fn yield_marginal(key: WeightKey, state: &GameState, idx: u8, w: &Weights, late: Option<f64>) -> f64 {
    match restricted_to_feature(key) {
        None => rivals::feature_marginal(key, state, idx, w, late, None),
        Some((feat, credit)) => {
            let c = match credit {
                RestrictedCredit::Fixed(v) => v,
                RestrictedCredit::Weight(k) => w.get(k),
            };
            if c == 0.0 {
                0.0
            } else {
                c * rivals::feature_marginal(feat, state, idx, w, late, None).max(0.0)
            }
        }
    }
}


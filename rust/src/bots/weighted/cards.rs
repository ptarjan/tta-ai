// ------------------------------------------------------------------ triples

/// The third slot of a yield triple -- mirrors Python's `_Y_GAIN`/`_Y_COST`/
/// `_Y_RATE`/`_Y_UNIT`/`_Y_TERR`/`_Y_BONUS` (plain `int` constants there,
/// because `_sum_yields` is the only reader and a bare `int` was enough to
/// switch on). A real enum here for the same reason [`super::weights::
/// WeightKey`] is one instead of a string: [`sum_yields`]'s `match` below is
/// exhaustive, so a seventh kind added later is a compile error at every
/// place that needs to know how to price it, not a silent `else` branch.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum YieldKind {
    /// Priced straight through `w[key]` -- one-shot gains and permanent
    /// modifiers printed on the card.
    Gain,
    /// Priced through `max(0.0, w[key])` -- `science`/`resource_stock` are
    /// STOCK weights a hill climb is free to drive negative (the 4p champion
    /// reached `science = -6.09`), and paying a cost must never read as a
    /// gain because of it.
    Cost,
    /// The short `culture`/`science` spelling (a wonder's per-turn rate,
    /// the headline omission docs/ANALYSIS_HISTORY.md's CARD_BLINDNESS.md
    /// entry describes) -- scaled by
    /// `card_rate_credit`, resolved once by [`sum_yields`]'s caller and
    /// threaded through as the `credit` argument, so the A/B against the
    /// pre-fix pricing is one knob.
    Rate,
    /// A military unit's per-worker `strength` (the top-level field a
    /// worker's `production` block never held) -- scaled by
    /// `unit_strength_credit`.
    Unit,
    /// A territory's `immediateEffects`/`permanentEffects` -- scaled by
    /// `territory_credit`.
    Territory,
    /// A Military Bonus card's defence/colonization numbers -- scaled by
    /// `bonus_card_credit`.
    Bonus,
}

/// `(feature, amount, kind)` -- what one line of a card's printed data is
/// worth, before a weight vector prices it. `WeightKey`, not a board-yields
/// [`crate::bots::board_yields::Feature`]: every triple here is fed straight
/// into `w.get(key)` ([`sum_yields`]) or, for the two ring-fenced pseudo-
/// features, into `feature_marginal` ([`yield_marginal`]) -- the same
/// weight-vector namespace `evaluate` itself indexes, not the narrower
/// swap-diff vocabulary `board_yields.rs` emits.
pub type CardYield = (WeightKey, f64, YieldKind);

/// Push `(key, amount, kind)` if `amount` is nonzero. Python's `_card_yields`
/// appends every triple it finds unconditionally (a zero-valued production
/// entry never appears in the printed data in the first place, so the two
/// are equivalent in practice); skipping a zero here is a cheap early-out on
/// [`crate::cards::CARDS`]'s otherwise mostly-zero `CardEffects` structs, not
/// a behaviour change -- [`sum_yields`]'s own `if amt != 0.0` guard would
/// have discarded it anyway.
#[inline]
fn push(out: &mut Vec<CardYield>, key: WeightKey, amount: i32, kind: YieldKind) {
    if amount != 0 {
        out.push((key, amount as f64, kind));
    }
}

// -------------------------------------------------------------- card_yields

/// `_card_yields`: every `(feature, amount, kind)` triple `name` prints,
/// independent of weights or board -- a pure function of card identity.
///
/// Pushes into `out` rather than returning a fresh `Vec` (DESIGN.md rule 4:
/// this runs for every card in every hand on every 1-ply candidate, so the
/// caller owns one scratch buffer for a whole evaluation and clears it
/// between cards -- `out.clear()` is the caller's job, not this function's,
/// so a caller that wants to ACCUMULATE across several cards can).
///
/// Python `lru_cache`s this per card name forever, because `C.db().by_name
/// .get(name)` is a dict lookup on a cold path relative to the rest of
/// evaluation. There is no dict here to cache the result of walking --
/// [`CardId::get`] is an array index into a `'static` table, and the work
/// below is a fixed handful of field reads and comparisons, cheaper than the
/// `HashMap` Python's cache itself would cost in Rust (DESIGN.md rule 1: no
/// process-global mutable cache). Recomputed on every call, matching
/// `horizon.rs`'s and `board_yields.rs`'s own "no memo cache" precedent.
pub fn card_yields(id: CardId, out: &mut Vec<CardYield>) {
    let card = id.get();
    let kind = card.kind;
    let eff = &card.effects;
    let prod = &card.production;

    // `_PROD_TO_FEATURE`: printed per-worker yield, always a flat gain --
    // farms/mines/urban buildings' `production` block, scaled by workers
    // elsewhere (`effects.rs`), priced here at its FACE value (one worker).
    push(out, WeightKey::CultureRate, prod.culture as i32, YieldKind::Gain);
    push(out, WeightKey::ScienceRate, prod.science as i32, YieldKind::Gain);
    push(out, WeightKey::FoodRate, prod.food as i32, YieldKind::Gain);
    push(out, WeightKey::ResourceRate, prod.resources as i32, YieldKind::Gain);
    push(out, WeightKey::HappyMargin, prod.happy as i32, YieldKind::Gain);
    push(out, WeightKey::Strength, prod.strength as i32, YieldKind::Gain);

    // `_UNIT_TO_FEATURE`: a military unit's per-worker STRENGTH, printed at
    // the card's top level in Python (never in `production`) and folded into
    // `effects.strength` here -- see this module's top doc comment. Ten
    // cards; all ten priced as pure cost before this bucket existed
    // (docs/ANALYSIS_HISTORY.md, CARD_BLINDNESS.md verdict).
    if kind.is_unit() {
        push(out, WeightKey::Strength, eff.strength as i32, YieldKind::Unit);
    }

    if kind == CardType::Territory {
        // `_TERR_TO_FEATURE`: a territory's `immediateEffects` (one-shot,
        // paid the moment the colony is claimed) and `permanentEffects`
        // (ongoing) -- both fused into `effects`/`immediate_effects` on the
        // Rust side (see this module's top doc comment), both credited
        // through `territory_credit` so the pre-fix pricing (0.0 for every
        // territory) is one knob away. Every field below is the exhaustive
        // set the live 12 territory cards ever set (census, 2026-08-05):
        // `permanentEffects` never prints `civilActions`/`militaryActions`/
        // `food`/`resources`/`cultureProduction`/`scienceProduction` today,
        // only `strength`/`happiness`/`yellowTokens`/`blueTokens` -- but
        // every field is read regardless, exactly as Python's block walk
        // would read whichever keys a future territory printed.
        push(out, WeightKey::Strength, eff.strength as i32, YieldKind::Territory);
        // `happy`/`happiness` -> `happy_margin`, NOT the bare `happy` weight
        // (which does not exist) -- the one substitution `_TERR_TO_FEATURE`
        // makes on top of `_YIELD_TO_FEATURE`, and it is required: `features
        // ()` resolves `happy` by hand into `happy_margin` and nothing else
        // ever reads a `"happy"` coordinate.
        push(out, WeightKey::HappyMargin, eff.happy as i32, YieldKind::Territory);
        push(out, WeightKey::CivilActions, eff.civil_actions as i32, YieldKind::Territory);
        push(out, WeightKey::MilitaryActions, eff.military_actions as i32, YieldKind::Territory);
        push(out, WeightKey::YellowBank, eff.yellow_tokens as i32, YieldKind::Territory);
        push(out, WeightKey::BlueFree, eff.blue_tokens as i32, YieldKind::Territory);

        let imm = &card.immediate_effects;
        push(out, WeightKey::FoodStock, imm.food as i32, YieldKind::Territory);
        push(out, WeightKey::ResourceStock, imm.resources as i32, YieldKind::Territory);
        push(out, WeightKey::Culture, imm.culture as i32, YieldKind::Territory);
        push(out, WeightKey::Science, imm.science as i32, YieldKind::Territory);
        push(out, WeightKey::FreeWorkers, imm.population as i32, YieldKind::Territory);
        push(out, WeightKey::HandMilitary, imm.draw_military_cards as i32, YieldKind::Territory);
    } else {
        // `_EFF_TO_FEATURE`: the general `effects` block. A territory's own
        // `effects` dict is `{}` in the source data (everything it prints
        // lives in the two blocks above), so this whole branch is exactly
        // Python's "the general loop finds nothing on a territory" --
        // structural here rather than incidental.
        push(out, WeightKey::Culture, eff.gain_culture as i32, YieldKind::Gain);
        push(out, WeightKey::Science, eff.gain_science as i32, YieldKind::Gain);
        push(out, WeightKey::FoodStock, eff.gain_food as i32, YieldKind::Gain);
        push(out, WeightKey::ResourceStock, eff.gain_resources as i32, YieldKind::Gain);

        // `civilActions`/`militaryActions`: a genuine per-card grant on
        // every type EXCEPT a government, whose own action counts land in
        // these same two fields but are never read by `_card_yields` in
        // Python (top-level fields there; `gov_value`'s board-aware job) --
        // see this module's top doc comment.
        if kind != CardType::Government {
            push(out, WeightKey::CivilActions, eff.civil_actions as i32, YieldKind::Gain);
            push(out, WeightKey::MilitaryActions, eff.military_actions as i32, YieldKind::Gain);
        }

        // the short `culture`/`science` spelling: per-turn RATE gains,
        // separated from the flat-gain bucket only so `card_rate_credit` can
        // switch them off and recover the exact pre-fix (silently dropped)
        // pricing for the A/B -- docs/ANALYSIS_HISTORY.md's CARD_BLINDNESS.md
        // entry, the headline fix.
        push(out, WeightKey::CultureRate, eff.culture as i32, YieldKind::Rate);
        push(out, WeightKey::ScienceRate, eff.science as i32, YieldKind::Rate);

        // `strength`: skip entirely for a Tactic, and skip here for a unit
        // (already priced above as `YieldKind::Unit` -- pushing it again
        // here would double-count the exact same field). A tactic's
        // top-level `strength` (its per-army bonus) is folded into this same
        // field -- see this module's top doc comment -- but it is
        // DELIBERATELY UNPRICED: `effects.tacticBonus`/`tacticBonusObsolete`
        // are a duplicate spelling of it, board-scaled (armies you can
        // FORM), and priced instead by `tactic_gain`/`tactic_short` off
        // `effects::tactic_outlook` (the valuation layer, not this file).
        // Every other type's `effects.strength` (special-tech, wonder,
        // leader) is a genuine flat gain.
        if kind != CardType::Tactic && !kind.is_unit() {
            push(out, WeightKey::Strength, eff.strength as i32, YieldKind::Gain);
        }
        push(out, WeightKey::HappyMargin, eff.happy as i32, YieldKind::Gain);
        push(out, WeightKey::YellowBank, eff.yellow_tokens as i32, YieldKind::Gain);
        push(out, WeightKey::BlueFree, eff.blue_tokens as i32, YieldKind::Gain);
        push(out, WeightKey::HandLimit, eff.civil_hand_limit as i32, YieldKind::Gain);
        push(out, WeightKey::HandLimit, eff.military_hand_limit as i32, YieldKind::Gain);
        push(out, WeightKey::ColonizeBonus, eff.colonize_bonus as i32, YieldKind::Gain);
        // `resource_discount`/`resources_for_military_units` are DELIBERATELY
        // not pushed here. Both fields exist only on Action cards
        // (`data/cards_military_actions.json`), which `card_potential`
        // dispatches to `action_value` on every live champion today
        // (`action_board_credit != 0.0` on all three trained vectors) --
        // `action_value` already prices both, through `yield_marginal`'s
        // ring-fenced reroute through `resource_stock`'s marginal, not
        // through the flat `w[resource_discount]`/`w[restricted_resources]`
        // lookup this function used to do. That used to be a SECOND,
        // disagreeing formula for the same two coordinates, live only in the
        // `action_board_credit == 0.0` edge case -- but genuinely live: on
        // the live 2p Rust champion (`experiments/rust_champion_2p.json`,
        // loaded through `eval::load_weights`) the two formulas priced Rich
        // Land (A)'s `resourceDiscount` at 0.0 (static -- `dominance_repair`
        // clamps the persisted `resource_discount = -0.0516` to 0.0 on load,
        // since it is a `BENEFIT_GATES` member and a printed benefit may
        // never price negative) vs 1.82 (board-aware, `resource_stock`'s own
        // marginal). Not a rounding difference -- the static formula called
        // this card worthless where the board-aware one found real value,
        // because the static formula rode a weight (`resource_discount`)
        // that `features()` never emits, so the league could only ever
        // random-walk it, never climb it toward agreement.
        // See `card_yields_never_reprices_the_action_boards_ring_fenced_
        // coordinates` below for the regression pin.
    }

    // `_BONUS_TO_FEATURE`: the three Military Bonus cards. `defenseBonus` is
    // priced as the INCREMENT over the flat +1 every military card is worth
    // face down (`hand_military` already carries that flat count) --
    // pricing the printed 2/4/6 would double-count the generic discard
    // value. `colonizationBonus` shares `colonize_bonus` with the general
    // `colonizeBonus` key above (`interact.force_value` sums both into the
    // same total, `features()` publishes it once) -- distinct FIELDS
    // (`colonization_bonus` vs `colonize_bonus`) so there is no risk of the
    // two colliding even though they share a target weight.
    if kind == CardType::Bonus {
        push(out, WeightKey::DefenseBonus, eff.defense_bonus as i32 - 1, YieldKind::Bonus);
        push(out, WeightKey::ColonizeBonus, eff.colonization_bonus as i32, YieldKind::Bonus);
    }

    // `_EFF_SPECIAL["wonderStagesPerAction"]`: printed as the TOTAL stages
    // per action (2); one is the base rate every card already has, so the
    // priced amount is the increment.
    if eff.wonder_stages_per_action > 1 {
        push(out, WeightKey::WonderStagesPerAction, eff.wonder_stages_per_action as i32 - 1, YieldKind::Gain);
    }

    for &sp in card.special {
        match sp {
            // `_EFF_SPECIAL["buildDiscount"]`: MAX, not sum -- `buildDiscount`
            // is `{age: resources off}` and a build is of exactly one age,
            // so the ages are ALTERNATIVES. `effects::build_cost` does a
            // single `bd[card.age]` lookup; summing would price a card at
            // something the rules engine never pays out (and get the three
            // Construction techs' relative order wrong: 3:5:6 instead of
            // 1:2:3). `[i16; 5]` is indexed by `Age as u8`, all five slots
            // always present (0 where unprinted), so a plain `max` over the
            // array is exactly Python's `max(bd.values())` over the
            // populated subset -- the unprinted ages are never the max
            // unless every age is 0, in which case there is nothing to gain
            // either way.
            Special::BuildDiscount(ages) => {
                let m = ages.iter().copied().max().unwrap_or(0);
                push(out, WeightKey::BuildDiscount, m as i32, YieldKind::Gain);
            }
            // `Special::FreeCivilAction` is DELIBERATELY not priced here.
            // `WeightKey::FreeCivilAction` used to be pushed as a flat 1.0
            // gain -- a second, disagreeing formula for the exact same
            // eighteen action cards `action_value` already prices through
            // `free_action_credit` (a civil action's own board-aware
            // marginal, gated so playing the action card's own spent civil
            // action doesn't get counted as a wash-turned-gain). Only
            // reachable when `action_board_credit == 0.0`, which no live
            // champion's trained vector has ever been (see this function's
            // `resource_discount` comment above for the same shape and a
            // measured disagreement). `WeightKey::FreeCivilAction` stays
            // in the registry as a known-dead coordinate; nothing pushes it
            // anymore.
            _ => {}
        }
    }

    // costs: `techCost`/`buildCost`, `_Y_COST` (clamped to `max(0, w)` by
    // `sum_yields` so a hill-climbed-negative stock weight can never make a
    // cost read as a gain -- see `YieldKind::Cost`'s own doc comment).
    if card.science_cost != 0 {
        out.push((WeightKey::Science, -(card.science_cost as f64), YieldKind::Cost));
    }
    if card.resource_cost != 0 {
        out.push((WeightKey::ResourceStock, -(card.resource_cost as f64), YieldKind::Cost));
    }

    if kind == CardType::Wonder {
        out.push((WeightKey::Wonders, 1.0, YieldKind::Gain));
        if !card.stages.is_empty() {
            let sum: u32 = card.stages.iter().map(|&s| s as u32).sum();
            out.push((WeightKey::ResourceStock, -(sum as f64), YieldKind::Cost));
        }
    }
}

/// `_card_choices`: `name`'s mutually-exclusive alternative, if it has one --
/// `_card_yields` SUMS everything it finds, which is wrong for a card that
/// makes you pick, not take both. Today's only instance is Reserves (I/II/
/// III): "gain N food OR N resources" (`Special::GainFoodOrResources`).
///
/// `Option<(CardYield, CardYield)>`, not a `Vec` of `Vec`s of alternatives:
/// Python's shape is general (a tuple of arbitrary-width groups, each an
/// arbitrary-width tuple of triples) because it is threaded through the same
/// untyped-dict machinery as everything else in the Python module, but there
/// has only ever been ONE choice card shape in the base game since this was
/// written, and DESIGN.md rule 4 says not to allocate a `Vec` for a value
/// this narrow. A future card that printed a three-way choice, or a choice
/// between more than one triple per branch, would need to widen this return
/// type -- which is a compile error at every caller, not a silent width
/// mismatch the way growing Python's tuple-of-tuples would be.
///
/// The caller (valuation layer, not ported here) takes the max of the two
/// branches' [`sum_yields`], e.g. `sum_yields(&[a], w, credit).max(sum_yields
/// (&[b], w, credit))`.
pub fn card_choice(id: CardId) -> Option<(CardYield, CardYield)> {
    id.get().special.iter().find_map(|&sp| match sp {
        Special::GainFoodOrResources(amt) if amt != 0 => Some((
            (WeightKey::FoodStock, amt as f64, YieldKind::Gain),
            (WeightKey::ResourceStock, amt as f64, YieldKind::Gain),
        )),
        _ => None,
    })
}

// --------------------------------------------------------------- sum_yields

/// `_sum_yields`: total eval-points a set of yield triples is worth at
/// weight vector `w`, crediting the short `culture`/`science` RATE spelling
/// at `credit` (`w.get(card_rate_credit)`, resolved ONCE by the caller and
/// threaded through here -- `card_potential` may call this several times per
/// card while pricing board terms, and re-reading the same weight each time
/// would be pure waste).
///
/// Python memoizes the other four credited kinds' weight lookups in a local
/// `dict` within one call, because `w.get(key, default)` there is a
/// `dict.get`. [`Weights::get`](super::weights::Weights::get) is a
/// bounds-checked array index, already as cheap as a memoized read would be,
/// so there is nothing here for a per-call cache to buy back -- reading
/// `w.get(WeightKey::UnitStrengthCredit)` twice in one card's triples (rare:
/// at most one `YieldKind::Unit` triple exists per card today) costs the
/// same as reading it once.
pub fn sum_yields(triples: &[CardYield], w: &Weights, credit: f64) -> f64 {
    let mut total = 0.0;
    for &(key, amount, kind) in triples {
        let mut wk = w.get(key);
        let mut amt = amount;
        match kind {
            YieldKind::Gain => {}
            YieldKind::Cost => {
                if wk < 0.0 {
                    wk = 0.0;
                }
            }
            YieldKind::Rate => amt *= credit,
            YieldKind::Unit => amt *= w.get(WeightKey::UnitStrengthCredit),
            YieldKind::Territory => amt *= w.get(WeightKey::TerritoryCredit),
            YieldKind::Bonus => amt *= w.get(WeightKey::BonusCardCredit),
        }
        if wk != 0.0 && amt != 0.0 {
            total += wk * amt;
        }
    }
    total
}


//! `engine/bots/weighted.py` lines 1730-3211: card, hand and wonder pricing --
//! what a card in hand or a wonder in progress is worth, board-aware.
//!
//! Two layers, landed in two passes and still split in the module's own
//! layout below (yield-plumbing first, valuation second) even though both
//! are now in one file:
//!
//! * YIELD-PLUMBING (landed first, commit `009f756`): turning one card's
//!   printed numbers into `(feature, amount, kind)` triples and summing them
//!   at a weight vector -- [`card_yields`]/[`card_choice`]/[`sum_yields`]/
//!   [`board_credit_key`]/[`swap_type`]/[`yield_marginal`] and the
//!   [`DELIBERATELY_UNPRICED`]/[`UNPRICED_VALUES`] tables. Board-independent
//!   except where noted.
//! * VALUATION (this pass): what a card in hand, a wonder in progress, or a
//!   whole hand is worth ON A BOARD -- [`action_value`]/[`tech_value`]/
//!   [`gov_value`] (the three civil types the static plumbing table alone
//!   prices badly or not at all), [`card_potential`] (the one entry point
//!   `eval.rs`/`row.rs` call, dispatching to the three above or falling back
//!   to the static table), [`hand_potential`]/[`hand_mil_potential`]/
//!   [`rival_hand_potential`]/[`wonder_potential`] (summed/maxed
//!   `card_potential` over a hand, a rival's hand, or the wonder in
//!   progress), and [`tactic_terms`] (the one term here that reaches into
//!   `effects::tactic_outlook`/`army_strength` rather than the yield-plumbing
//!   layer -- see its own doc comment).
//!
//! ## The type system already fixed the bug this file exists to prevent
//!
//! Python's `_card_yields` walks `card.get("effects") or {}` -- a raw
//! `dict[str, Any]` -- against two hand-maintained lookup tables
//! (`_EFF_TO_FEATURE`, `_PROD_TO_FEATURE`), plus a top-level-field special
//! case for units and a per-block special case for territories. The entire
//! second half of the Python module's own doc comments (`DELIBERATELY_UNPRICED`
//! and every test in `tests/test_card_pricing.py`) exists to catch a key
//! silently falling through that walk -- `culture`/`science` on ten wonders
//! did, for most of the project's life, because nothing failed when they did.
//!
//! `crate::cards::CardEffects` (generated by `tools/gen_cards.py` from the
//! same underlying data) already closes that hole a level down: every
//! recurring effect key is a named, typed field, and a key `gen_cards.py`
//! cannot classify stops the BUILD, not a test run days or months later. So
//! this file reads typed fields (`card.effects.culture`, `card.effects
//! .strength`, ...) instead of walking a dict, and the Python tables
//! (`_PROD_TO_FEATURE`/`_EFF_TO_FEATURE`/`_TERR_TO_FEATURE`/
//! `_UNIT_TO_FEATURE`/`_BONUS_TO_FEATURE`) collapse into the `match`/`if`
//! structure of [`card_yields`] below -- there is no dict to keep in sync
//! with a card table that no longer exists as a dict either.
//!
//! One consequence worth flagging explicitly: `gen_cards.py` FUSES several
//! Python dict keys that mean different things into the SAME typed field,
//! because they feed the same `Stats` slot in `effects.rs`:
//!
//! * `CardEffects.strength` is Python's top-level `card["strength"]` on a
//!   unit card (per-worker rate), a genuine `effects.strength` key on
//!   everything else, AND the top-level `strength` a TACTIC also prints
//!   (`effects.tacticBonus`'s duplicate spelling, DELIBERATELY_UNPRICED
//!   bucket 5) -- three different meanings sharing one field. [`card_yields`]
//!   dispatches on [`crate::cards::CardType::is_unit`] first (unit ->
//!   `YieldKind::Unit`), skips `CardType::Tactic` entirely (never priced,
//!   matching Python), and prices everything else as a flat gain.
//! * `CardEffects.strength`/`.happy`/`.civil_actions`/`.military_actions`/
//!   `.blue_tokens`/`.yellow_tokens` are ALSO where a territory's
//!   `permanentEffects` land (a territory's own `effects` dict is `{}` in
//!   the source data -- see the Python source's own note on `_TERR_TO_FEATURE`
//!   for why that is not a coincidence: `deferred_credit`, the auction path,
//!   prices the identical two blocks). [`card_yields`] dispatches on
//!   `CardType::Territory` before reading any of these six fields, so a
//!   territory's flat numbers are priced through `territory_credit`
//!   (`YieldKind::Territory`) and never double-counted as a bare gain.
//! * `CardEffects.civil_actions`/`.military_actions` are ALSO where a
//!   GOVERNMENT's top-level action counts land (RULES_SPEC 8.1) -- Python's
//!   `_card_yields` never reads these for a government (they are top-level
//!   fields on the Python card dict, not inside `effects`; see
//!   `tests/test_card_pricing.py`'s `TOP_LEVEL_UNPRICED["civilActions"]`).
//!   [`card_yields`] skips both fields for `CardType::Government`, leaving a
//!   government's action counts to the valuation layer's `gov_value` (which
//!   reads them board-aware, through `board_yields::government_plans`).
//!
//! `effects.free_civil_action` and `effects.on_build_culture` are dead
//! fields (always `0` on every one of the 236 base-game cards): the
//! `freeCivilAction`/`onBuildCulture` keys are STRINGS/booleans in the
//! source data (which action, not how many; whether, not how much), so
//! `gen_cards.py` routes them through [`crate::cards::Special`] instead --
//! `Special::FreeCivilAction` (a presence flag, matching Python's
//! `_EFF_SPECIAL["freeCivilAction"]` treatment exactly) and
//! `Special::OnBuildCulture` (board-priced, `board_yields.rs`'s concern, not
//! this file's -- Python's own `_card_yields` never prices it either).
//!
//! ## The yield-plumbing layer's own API, restated
//!
//! * [`card_yields`]/[`card_choice`]/[`sum_yields`] -- the pricing table
//!   itself. [`card_yields`] pushes into a caller-supplied `&mut Vec`
//!   (DESIGN.md rule 4: this is called for every card in every hand on every
//!   evaluation, so the caller owns one scratch buffer across the whole
//!   evaluation and clears it between cards rather than each call
//!   allocating) -- [`card_potential`] below is that caller, threading its
//!   own `scratch` parameter down for exactly this reason. [`card_choice`] is
//!   `Option<(CardYield, CardYield)>`, not a `Vec` of alternatives --
//!   today's only mutually-exclusive card (Reserves,
//!   `Special::GainFoodOrResources`, "N food OR N resources") is exactly a
//!   pair, and a hypothetical wider choice should widen the return type, not
//!   grow a `Vec` next to it.
//! * [`board_credit_key`]/[`swap_type`] -- board-pricing plumbing
//!   (`card_board_*` offsets, `SINGLE_SLOT`).
//! * [`yield_marginal`] -- `_yield_marginal`: [`rivals::feature_marginal`]
//!   plus the two ring-fenced pseudo-features (`resource_discount`/
//!   `restricted_resources`). Calls `feature_marginal` directly rather than
//!   through an injected closure -- `rivals.rs` had already landed by the
//!   time the yield-plumbing half of this file was written, so there was
//!   never a real dependency to inject a stand-in for. The `idx: u8` vs.
//!   `idx: usize` mismatch this exposed against `board_yields.rs` (flagged in
//!   an earlier revision of this comment) is gone: this pass unified both on
//!   `u8` (matching `GameState::current` and the rest of the engine) and
//!   removed the casts at the boundary -- see [`feature_key`] and every
//!   `board_yields::*` call below.
//! * [`crate::cards::CardType::is_unit`]/[`crate::bots::board_yields::
//!   is_levelled_type`]/[`crate::cards::CardType::is_action`]/
//!   [`crate::cards::CardType::is_government`] -- `_is_unit`/
//!   `_is_levelled_tech`/`_is_action`/`_is_government`. These are exhaustive
//!   `CardType` predicates, not functions of a card NAME, so they live on
//!   `CardType` itself (`is_unit`/`is_action`/`is_government`, the first two
//!   already ported this way for `board_yields.rs`; `is_action`/
//!   `is_government` added alongside this file) or, for `is_levelled_tech`,
//!   on `board_yields::is_levelled_type` where the sibling `is_swap_type`/
//!   `is_single_slot` predicates already live. There is no wrapper of the
//!   same name in this module -- a caller writes `id.kind().is_unit()`, not
//!   `cards::is_unit(id)`.
//! * [`DELIBERATELY_UNPRICED`]/[`UNPRICED_VALUES`] -- the documented gap, see
//!   their own doc comments below.

